--     FECHADO sem nº = "não importado" (a tela oferece importar depois).
ALTER TABLE ven_orcamento ADD COLUMN IF NOT EXISTS "orcamentoCelta"    INTEGER;
ALTER TABLE ven_orcamento ADD COLUMN IF NOT EXISTS celta_importado_em TIMESTAMPTZ;

-- 11) Acréscimo (19/09/2026): o vendedor pode cobrar o item acima da tabela. O desconto
--     da linha fica zero e a diferença (preço cobrado − tabela) × quantidade, em R$, é
--     gravada aqui. Campo só de banco/relatório: nenhuma tela, PDF ou o Celta o exibe.
ALTER TABLE ven_orcamento_item ADD COLUMN IF NOT EXISTS acrescimo NUMERIC(15,2) NOT NULL DEFAULT 0;

-- 12) ICMS na venda para fora do estado (24/09/2026): o orçamento mostra o imposto como a
--     nota vai sair. Cliente contribuinte de outro estado (indicador de IE 1): ICMS-ST por
--     item. Cliente não contribuinte/isento (9/2), venda não presencial: DIFAL por item, cobrado do
--     cliente como despesa acessória (acordo com os clientes do atacado). Os dois somam ao total
--     apresentado ao cliente (`total` continua sendo só a mercadoria; total ao cliente = total +
--     icms_st + difal); bolsa e margem não mudam (repasse).
--     `tributacao` guarda o regime aplicado (NENHUM | ST | DIFAL | PRESENCIAL | FORA_ESCOPO);
--     `presencial` é o mesmo indicador de presença da NF-e (padrão não presencial no atacado).
--     `difal_pct` NULL num item com regime DIFAL = produto sem alíquota cadastrada no Celta.
ALTER TABLE ven_orcamento ADD COLUMN IF NOT EXISTS presencial BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE ven_orcamento ADD COLUMN IF NOT EXISTS tributacao TEXT;
ALTER TABLE ven_orcamento ADD COLUMN IF NOT EXISTS icms_st    NUMERIC(15,2) NOT NULL DEFAULT 0;
ALTER TABLE ven_orcamento ADD COLUMN IF NOT EXISTS difal      NUMERIC(15,2) NOT NULL DEFAULT 0;
ALTER TABLE ven_orcamento_item ADD COLUMN IF NOT EXISTS icms_st   NUMERIC(15,2) NOT NULL DEFAULT 0;
ALTER TABLE ven_orcamento_item ADD COLUMN IF NOT EXISTS difal     NUMERIC(15,2) NOT NULL DEFAULT 0;
ALTER TABLE ven_orcamento_item ADD COLUMN IF NOT EXISTS difal_pct NUMERIC(6,4);

-- 13) Meia nota (24/09/2026): venda que sai metade em produto e metade em serviço. Só muda a
--     estimativa do imposto interestadual no orçamento: ST e DIFAL calculados sobre metade do
--     valor de cada item, e na importação ao Celta o valor vai em "Desp. Acessórias" em vez das
--     colunas de tributação. Estimativa comercial do que o cliente paga; a nota é do Celta.
ALTER TABLE ven_orcamento ADD COLUMN IF NOT EXISTS meia_nota BOOLEAN NOT NULL DEFAULT FALSE;

-- 14) Compra de oportunidade (25/09/2026): reserva da empresa na bolsa do vendedor. A gestão
--     registra a nota de compra e o % da sobra (tabela − custo × piso) que fica com o vendedor;
--     grava-se por produto o CUSTO PARA A BOLSA (fixo em R$) que a bolsa usa no lugar do custo
--     real enquanto o lote durar. Um registro por lote: registrar de novo encerra o anterior.
--     Encerra sozinho quando as unidades vendidas desde o registro chegam à quantidade.
CREATE TABLE IF NOT EXISTS ven_bolsa_oportunidade (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pro_codigo    INTEGER NOT NULL,
  descricao     TEXT,
  nfe           INTEGER,                          -- NF_ENTRADA.NFE (empresa 1)
  nota_fiscal   INTEGER,
  for_codigo    INTEGER,
  for_nome      TEXT,
  quantidade    NUMERIC(15,4) NOT NULL,           -- unidades do lote cobertas pela regra
  custo_nota    NUMERIC(15,4),                    -- custo do item na nota (informação)
  custo         NUMERIC(15,4) NOT NULL,           -- custo de reposição no dia do registro
  preco_tabela  NUMERIC(15,2) NOT NULL,           -- PRECO2 no dia do registro
  piso          NUMERIC(8,4)  NOT NULL,           -- piso da bolsa no dia do registro
  pct_vendedor  NUMERIC(5,4)  NOT NULL,           -- fração da sobra que fica com o vendedor
  custo_bolsa   NUMERIC(15,4) NOT NULL,           -- custo que a bolsa usa (fixo em R$)
  vigente_de    DATE NOT NULL,                    -- vendas a partir deste dia
  vendida       NUMERIC(15,4) NOT NULL DEFAULT 0, -- apurada no BI (todos os canais, devolução desconta)
  apurado_em    TIMESTAMPTZ,
  encerrado_em  DATE,                             -- vendas a partir deste dia voltam ao custo real
  criado_por    TEXT,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ven_bolsa_oportunidade_pro_idx ON ven_bolsa_oportunidade (pro_codigo);

-- 15) Venda perdida pela pesquisa de produtos (26/09/2026): o vendedor aperta F7 no item sem saldo
--     e registra a perda sem pôr o item no orçamento. O registro nasce sem orçamento (cliente,
--     vendedor, produto, quantidade 1, motivo SEM_SALDO, similar/justificativa); se o mesmo item
--     cair como venda perdida no Fechou do dia, o serviço amarra este registro ao orçamento em vez
--     de criar outro. Sem orçamento vale UM por cliente + produto + dia (dia de Cuiabá).
ALTER TABLE ven_venda_perdida ALTER COLUMN orcamento_id DROP NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_ven_venda_perdida_pesquisa_dia
  ON ven_venda_perdida (cli_codigo, pro_codigo, ((created_at AT TIME ZONE 'America/Cuiaba')::date))
  WHERE orcamento_id IS NULL;

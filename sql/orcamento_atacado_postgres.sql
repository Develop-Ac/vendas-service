-- ============================================================================
-- Orçamento do Atacado (plano de precificação v3) — DDL PostgreSQL
-- Aplicar MANUALMENTE (não usar prisma migrate). Idempotente.
--
-- O ERP (Celta/Firebird) continua a fonte da verdade de cadastro, saldo e
-- tabela de preço; o BI, a fonte da venda realizada. O que mora aqui é o que
-- o ERP não tem:
--   ven_regua_atacado        -> a régua v3: classe (GERAL | PB) × faixa (1A..3D)
--                                = markup de lista + desconto máximo do vendedor.
--   ven_regua_item_excecao   -> itens fora da régua (LANÇAMENTO/EXCLUSIVO e
--                                COMPRA DE OPORTUNIDADE): markup atual congelado,
--                                desconto máximo próprio. Revisão mensal.
--   ven_orcamento            -> o orçamento feito NA INTRANET (cabeçalho).
--   ven_orcamento_item       -> os itens, com a fotografia da régua no momento
--                                (classe, faixa, desc. máx, preço mínimo, custo).
--   ven_produto_relacionado  -> "vendem juntos": pares apurados no BI (12 meses
--                                do atacado), recalculados por cron semanal.
-- ============================================================================

-- 1) Régua v3 -----------------------------------------------------------------
CREATE TABLE IF NOT EXISTS ven_regua_atacado (
  id          SERIAL PRIMARY KEY,
  classe      TEXT NOT NULL,                       -- GERAL | PB
  faixa       TEXT NOT NULL,                       -- 1A 1B 1C 1D 2A 2B 2C 3A 3B 3C 3D
  markup      NUMERIC(6,3) NOT NULL,               -- preço de lista = custo × markup
  desc_max    NUMERIC(5,4) NOT NULL,               -- desconto máximo do vendedor (0.03 = 3%)
  ativo       BOOLEAN NOT NULL DEFAULT TRUE,
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_ven_regua_atacado UNIQUE (classe, faixa)
);

